/** Character → its toneless readings. Built on first use. */
function readings(ch: string): string[] | undefined {
  if (!index) {
    index = new Map();
    for (const entry of TABLE.split(/\s+/)) {
      const at = entry.indexOf(':');
      if (at <= 0) continue;
      const syllable = entry.slice(0, at);
      for (const c of entry.slice(at + 1)) {
        const list = index.get(c);
        if (list) list.push(syllable);
        else index.set(c, [syllable]);
      }
    }
  }
  return index.get(ch);
}

/** Same character, or two Chinese characters sharing a reading (tones ignored). Latin letters compare case-insensitively. */
export function sameSound(a: string, b: string): boolean {
  if (a === b || a.toLowerCase() === b.toLowerCase()) return true;
  const ra = readings(a);
  if (!ra) return false;
  const rb = readings(b);
  return Boolean(rb && ra.some((r) => rb.includes(r)));
}
